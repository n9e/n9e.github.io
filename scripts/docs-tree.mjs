// doc() 的第二、三个参数是 [标题, 摘要]。**摘要只在首次生成占位页时用得到**
// （scaffold-docs.mjs 的 stub() 会把它写进 front matter 的 description），
// 之后正文文件里那一份才是权威——页面写完后改这里不会有任何效果。
// 所以标了 { existing: true } 的节点，摘要留着只是给人看目录时有个印象，
// 和正文对不上也不影响构建。别写脚本去「同步」它：这里的第一个字符串是标题，
// 很容易把标题覆盖成摘要。
const doc = (id, en, zh, extra = {}) => ({
  type: 'doc',
  id,
  en: { label: en[0], scope: en[1], title: en[2] ?? en[0] },
  zh: { label: zh[0], scope: zh[1], title: zh[2] ?? zh[0] },
  ...extra,
});

const category = (key, en, zh, items, opts = {}) => ({
  type: 'category',
  key,
  en: { label: en[0], blurb: en[1] },
  zh: { label: zh[0], blurb: zh[1] },
  items,
  ...opts,
});

const link = (href, en, zh) => ({ type: 'link', href, en: { label: en }, zh: { label: zh } });

